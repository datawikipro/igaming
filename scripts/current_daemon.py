def run_agy_step(prompt, model, mode="accept-edits", working_dir="/workspace/repo", timeout_seconds=420):
    global active_process
    env = dict(os.environ)
    env["AGY_ACCEPT_TOS"] = "true"
    env["ANTIGRAVITY_ACCEPT_TOS"] = "true"
    env["AGY_SKIP_ONBOARDING"] = "true"
    env["ANTIGRAVITY_SKIP_ONBOARDING"] = "true"
    env["LANG"] = "C.UTF-8"
    env["LC_ALL"] = "C.UTF-8"
    env["PYTHONIOENCODING"] = "utf-8"
    env["PLAYWRIGHT_BROWSERS_PATH"] = "/ms-playwright"
    env["DISPLAY"] = os.environ.get("DISPLAY", ":99")


    cmd = [
        "agy",
        "-p", prompt,
        "--model", model,
        "--mode", mode,
        "--dangerously-skip-permissions",
        "--add-dir", working_dir
    ]
    if os.path.exists("/workspace/documentation"):
        cmd.extend(["--add-dir", "/workspace/documentation"])

    log(f"Running agy (model: {model}, mode: {mode}, dir: {working_dir})...")
    try:
        active_process = subprocess.Popen(
            cmd,
            cwd=working_dir,
            env=env,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            preexec_fn=os.setsid
        )
        stdout, stderr = active_process.communicate(timeout=timeout_seconds)
        ret = active_process.returncode
        active_process = None
        output = (stdout or "") + "\n" + (stderr or "")
        
        # Automatic fallback to Claude Sonnet 4.6 if Gemini runs out of quota
        lower_out = output.lower()
        if model == MODEL_GEMINI and any(k in lower_out for k in ["quota exceeded", "resource_exhausted", "out of credits", "429", "eligibility check failed"]):
            log("Quota limit detected on Gemini! Seamlessly falling back to Claude Sonnet 4.6 Thinking...")
            return run_agy_step(prompt, "claude-sonnet-4-6", mode=mode, working_dir=working_dir, timeout_seconds=timeout_seconds)
            
        return ret, output
    except subprocess.TimeoutExpired:
        log(f"Step timed out after {timeout_seconds}s. Terminating agy process group and capturing partial progress...")
        if active_process:
            try:
                os.killpg(os.getpgid(active_process.pid), signal.SIGKILL)
                active_process.wait(timeout=5)
            except Exception:
                pass
            active_process = None
        return 0, "timeout_partial_checkpoint"

def deploy_and_verify_e2e(repo_dir, task, task_title, short_id, target_branch, base_branch, email, git_repo):
    """
    Autonomous E2E Delivery Pipeline:
    1. Detect changed module / bookmaker
    2. Maven compile + Jib build container image for testing
    3. Run in a separate TEST POD in Kubernetes (namespace: igaming-source)
    4. 5-minute Soak Test on the test pod (clean logs, odds/matches active)
    5. Clean up test pod
    6. Commit & Merge PR / branch into base_branch (master)
    7. Push image as :latest and Deploy to PROD (rollout restart)
    8. 5-minute Monitoring on PROD pod (clean logs, real odds coming)
    9. Report success to Plane ("???? ???? ??????????????!...")
    """
    log(f"=== Starting E2E Delivery Pipeline for #{short_id}: {task_title} ===")
    
    # 1. Detect module and bookmaker
    module_name = None
    diff_res = subprocess.run(["git", "diff", "--name-only", f"origin/{base_branch}", "HEAD"], cwd=repo_dir, capture_output=True, text=True)
    for line in diff_res.stdout.splitlines():
        part = line.split("/")[0]
        if os.path.isdir(os.path.join(repo_dir, part)) and (part.startswith("igaming-") or part == "smartbet.guru" or part.startswith("service-")):
            module_name = part
            break
            
    if not module_name:
        match = re.search(r"\[([^\]]+)\]", task_title)
        if match:
            tag = match.group(1).lower().strip()
            for d in os.listdir(repo_dir):
                if os.path.isdir(os.path.join(repo_dir, d)) and tag in d.lower():
                    module_name = d
                    break

